'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('host', {
  tileCache: true,
  noticesText: () => ipcRenderer.invoke('app:noticesText'),
  openDialog: (opts) => ipcRenderer.invoke('dlg:open', opts),
  saveDialog: (opts) => ipcRenderer.invoke('dlg:save', opts),
  message: (opts) => ipcRenderer.invoke('dlg:message', opts),
  readText: (p) => ipcRenderer.invoke('fs:readText', p),
  writeText: (p, t, enc) => ipcRenderer.invoke('fs:writeText', p, t, enc),
  encoding: (p) => ipcRenderer.invoke('fs:encoding', p),
  readBinary: (p) => ipcRenderer.invoke('fs:readBinary', p),
  writeBinary: (p, d) => ipcRenderer.invoke('fs:writeBinary', p, d),
  exists: (p) => ipcRenderer.invoke('fs:exists', p),
  info: () => ipcRenderer.invoke('app:info'),
  prepareSample: (n) => ipcRenderer.invoke('app:prepareSample', n),
  getSettings: () => ipcRenderer.invoke('app:settings:get'),
  licenseVerify: (k) => ipcRenderer.invoke('license:verify', k),
  licenseMachine: () => ipcRenderer.invoke('license:machine'),
  licenseIssue: (pem, lic) => ipcRenderer.invoke('license:issue', pem, lic),
  setSettings: (s) => ipcRenderer.invoke('app:settings:set', s),
  listDir: (d) => ipcRenderer.invoke('fs:list', d),
  drives: () => ipcRenderer.invoke('fs:drives'),
  paths: () => ipcRenderer.invoke('app:paths'),
  readZip: (p) => ipcRenderer.invoke('zip:read', p),
  gdalAvailable: () => ipcRenderer.invoke('gdal:available'),
  gdal: (tool, args) => ipcRenderer.invoke('gdal:run', tool, args),
  tempDir: () => ipcRenderer.invoke('app:tempDir'),
  rm: (p) => ipcRenderer.invoke('fs:rm', p),
  mkdir: (p) => ipcRenderer.invoke('fs:mkdir', p),
  pathForFile: (f) => { try { return webUtils.getPathForFile(f); } catch (e) { return f && f.path; } },
  getUsers: () => ipcRenderer.invoke('app:users:get'),
  setUsers: (u) => ipcRenderer.invoke('app:users:set', u),
  hash: (pw, salt) => ipcRenderer.invoke('app:hash', pw, salt),
  openExternal: (u) => ipcRenderer.invoke('app:openExternal', u),
  showItem: (p) => ipcRenderer.invoke('app:showItem', p),
  setTitle: (t) => ipcRenderer.send('app:set-title', t),
  confirmClose: () => ipcRenderer.send('app:close-confirmed'),
  onRequestClose: (cb) => ipcRenderer.on('app:request-close', () => cb()),
  onOpenFile: (cb) => ipcRenderer.on('app:open-file', (e, p) => cb(p)),
  engineVersion: () => ipcRenderer.invoke('engine:version'),
  runEngine: (job) => ipcRenderer.invoke('engine:run', job),
  cancelEngine: (id) => ipcRenderer.invoke('engine:cancel', id),
  onProgress: (cb) => ipcRenderer.on('engine:progress', (e, p, id) => cb(p, id)),
  cpuInfo: () => ipcRenderer.invoke('sys:cpu'),
  rmRun: (files) => ipcRenderer.invoke('fs:rmRun', files),
  renameRun: (pairs) => ipcRenderer.invoke('fs:renameRun', pairs),
  outOpen: (f) => ipcRenderer.invoke('out:open', f),
  outClose: (h) => ipcRenderer.invoke('out:close', h),
  outSeries: (h, type, i, v) => ipcRenderer.invoke('out:series', h, type, i, v),
  outSnapshot: (h, per, type, v) => ipcRenderer.invoke('out:snapshot', h, per, type, v),
  outStats: (h, type, v) => ipcRenderer.invoke('out:stats', h, type, v),
  outSnapshotAll: (h, per, type) => ipcRenderer.invoke('out:snapshotAll', h, per, type),
  outStatsAll: (h) => ipcRenderer.invoke('out:statsAll', h),
  outPondStats: (h, idx, thr) => ipcRenderer.invoke('out:pondStats', h, idx, thr),
});
